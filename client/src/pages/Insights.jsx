/**
 * @fileoverview Smart Financial Insights view showing personalized AI and rule-based tips.
 */

import React, { useState, useEffect, useCallback } from 'react';
import apiClient from '../api/client.js';
import { formatMonthYear } from '../utils/formatters.js';
import Skeleton from '../components/common/Skeleton.jsx';
import EmptyState from '../components/common/EmptyState.jsx';

export default function Insights() {
  const currentMonth = new Date().toISOString().slice(0, 7);
  const [month, setMonth] = useState(currentMonth);
  const [tips, setTips] = useState([]);
  const [source, setSource] = useState('rules');
  const [loading, setLoading] = useState(true);

  const loadInsights = useCallback(async () => {
    setLoading(true);
    try {
      const res = await apiClient.get('/insights', { params: { month } });
      if (res?.data) {
        setTips(res.data.tips || []);
        setSource(res.data.source || 'rules');
      }
    } catch (err) {
      console.error('Failed to load insights:', err);
    } finally {
      setLoading(false);
    }
  }, [month]);

  useEffect(() => {
    loadInsights();
  }, [loadInsights]);

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '1.5rem', maxWidth: '850px', margin: '0 auto' }}>
      {/* Header */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', flexWrap: 'wrap', gap: '1rem' }}>
        <div>
          <h1 style={{ fontSize: '1.6rem', fontWeight: 700 }}>💡 Smart Financial Insights</h1>
          <p style={{ fontSize: '0.875rem', color: 'var(--text-secondary)' }}>
            Personalized intelligence and anomaly detection for {formatMonthYear(month)}
          </p>
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem' }}>
          <input
            type="month"
            className="form-control"
            value={month}
            onChange={(e) => setMonth(e.target.value)}
            style={{ width: '160px' }}
          />
          <button onClick={loadInsights} className="btn btn-secondary btn-icon" title="Refresh Analysis">
            🔄
          </button>
        </div>
      </div>

      {/* Engine Source Badge */}
      <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
        <span style={{ fontSize: '0.8rem', color: 'var(--text-secondary)' }}>Generated by:</span>
        <span className={`badge ${source === 'llm' ? 'badge-info' : 'badge-warning'}`}>
          {source === 'llm' ? '✨ Generative AI Engine (Gemini/OpenAI)' : '⚙️ Deterministic Rules Engine'}
        </span>
      </div>

      {/* Insights Cards List */}
      {loading ? (
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
          <Skeleton height="110px" />
          <Skeleton height="110px" />
          <Skeleton height="110px" />
        </div>
      ) : tips.length > 0 ? (
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
          {tips.map((tip, idx) => {
            const isDanger = tip.severity === 'danger';
            const isWarning = tip.severity === 'warning';

            const bg = isDanger ? 'var(--danger-bg)' : isWarning ? 'var(--warning-bg)' : 'var(--info-bg)';
            const border = isDanger ? 'var(--danger)' : isWarning ? 'var(--warning)' : 'var(--info)';
            const icon = isDanger ? '⚠️' : isWarning ? '⚡' : '💡';

            return (
              <div
                key={idx}
                className="card"
                style={{
                  background: bg,
                  borderLeft: `5px solid ${border}`,
                  padding: '1.25rem',
                }}
              >
                <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', marginBottom: '0.5rem' }}>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                    <span style={{ fontSize: '1.25rem' }}>{icon}</span>
                    <h3 style={{ fontSize: '1.05rem', fontWeight: 700, color: 'var(--text-primary)' }}>
                      {tip.title}
                    </h3>
                  </div>
                  <span
                    className="badge"
                    style={{
                      background: 'var(--bg-surface)',
                      color: border,
                      fontWeight: 600,
                      fontSize: '0.75rem',
                    }}
                  >
                    {tip.severity}
                  </span>
                </div>
                <p style={{ fontSize: '0.9rem', color: 'var(--text-secondary)', lineHeight: 1.6 }}>
                  {tip.message}
                </p>
              </div>
            );
          })}
        </div>
      ) : (
        <EmptyState
          icon="💡"
          title="No insights generated yet"
          message="Log additional expense transactions to provide sufficient data for analysis."
        />
      )}
    </div>
  );
}
